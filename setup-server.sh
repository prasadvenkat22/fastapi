#!/bin/bash
# Digital Ocean Droplet Setup Script
# Run this script on a fresh Ubuntu 24.04 droplet
# Usage: bash setup-server.sh (must be downloaded first, not piped, due to interactive prompts)

set -e

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m'

log_info() { echo -e "${GREEN}[INFO]${NC} $1"; }
log_warn() { echo -e "${YELLOW}[WARN]${NC} $1"; }
log_error() { echo -e "${RED}[ERROR]${NC} $1"; }
log_step() { echo -e "${BLUE}[STEP]${NC} $1"; }

echo ""
echo "========================================"
echo "  FastAPI Droplet Setup Script"
echo "  Digital Ocean - Ubuntu 24.04"
echo "========================================"
echo ""

# Check if running as root
if [ "$EUID" -ne 0 ]; then
    log_error "Please run as root: sudo bash setup-server.sh"
    exit 1
fi

# Step 1: Update system
log_step "1/7 - Updating system packages..."
apt update && apt upgrade -y
log_info "System updated."

# Step 2: Install Docker
log_step "2/7 - Installing Docker..."
if command -v docker &> /dev/null; then
    log_info "Docker already installed."
else
    curl -fsSL https://get.docker.com | sh
    systemctl enable docker
    systemctl start docker
    log_info "Docker installed and started."
fi

# Step 3: Install Docker Compose plugin
log_step "3/7 - Installing Docker Compose plugin..."
apt install docker-compose-plugin -y
log_info "Docker Compose plugin installed."

# Step 4: Configure firewall
log_step "4/7 - Configuring firewall..."
ufw allow OpenSSH
ufw allow 80/tcp
ufw allow 443/tcp
ufw allow 8000/tcp
ufw --force enable
log_info "Firewall configured."

# Step 5: Clone repository
log_step "5/7 - Cloning repository..."
APP_DIR="/opt/fastapi"
if [ -d "$APP_DIR" ]; then
    log_warn "Directory $APP_DIR already exists. Pulling latest changes..."
    cd $APP_DIR
    git pull origin main
else
    cd /opt
    git clone https://github.com/prasadvenkat22/fastapi.git
    cd $APP_DIR
fi
log_info "Repository ready at $APP_DIR"

# Step 6: Setup deploy script
log_step "6/7 - Setting up deployment scripts..."
chmod +x deploy.sh
log_info "Deploy script ready."

# Step 7: Setup environment file
log_step "7/7 - Setting up environment configuration..."
if [ ! -f ".env.production.example" ]; then
    log_error ".env.production.example template not found!"
    exit 1
fi

echo ""
echo "========================================"
echo "  Environment Configuration"
echo "========================================"
echo ""

# Prompt for essential configuration
read -p "Enter PostgreSQL password: " -s DB_PASSWORD
echo ""
read -p "Enter pgAdmin password: " -s PGADMIN_PASSWORD
echo ""
read -p "Enter OpenAI API Key: " -s OPENAI_KEY
echo ""
read -p "Enter your domain (or press Enter for IP only): " DOMAIN

# Generate secure JWT secret
JWT_SECRET=$(openssl rand -hex 32)

# Get external IP
EXTERNAL_IP=$(curl -s ifconfig.me)

