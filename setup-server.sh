# JWT/Auth Configuration
secret=${JWT_SECRET}
algorithm=HS256
ACCESS_TOKEN_EXPIRES_IN=15
REFRESH_TOKEN_EXPIRES_IN=60
JWT_ALGORITHM=RS256
CLIENT_ORIGIN=${DOMAIN:-http://${EXTERNAL_IP}}

